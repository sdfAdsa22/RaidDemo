namespace RaidDemo.Simulation
{
    /// <summary>
    /// 联机会话里的输入序号发号器：进程内单调递增、跨场景共用。
    /// </summary>
    /// <remarks>
    /// <para><b>为什么必须是进程级，而不是"每条链路一份"（U-98 的教训）：</b>
    /// 客户端的移动链路是**每张场景各建一个实例**的（安全屋一份、战局一份），
    /// 而服务器按"序号必须递增"过滤重复与乱序包。两条链路若各自从 0 重新计数，
    /// 就会撞上这段窗口：服务器端同一玩家的"已处理序号"已被旧链路的尾部输入顶到几百
    /// （旧链路的序号值本身已经很高），新链路的前几百条输入于是全部被当作重复包
    /// 静默丢弃——服务器把玩家留在出生点，客户端本地预测继续自由前进，
    /// 直到序号追平才用一次硬吸附把两端对齐。实机表现就是
    /// 「进图几秒后闪回出生点、闪回前弹道与准星不在一条线」。</para>
    ///
    /// <para><b>为什么不做在 <c>SessionScope</c> 上：</b>场景作用域每次换图都会被释放重建
    /// （换图正是要跨过的那条缝），序号必须活在它们之上；一个客户端进程只有一个本机玩家，
    /// 进程级静态就是最贴合的粒度。</para>
    ///
    /// <para><b>序号只要求单调：</b>服务器接受任何大于"已处理序号"的输入，因此
    /// 跨场景、跨重连（同进程）连续递增都合法；进程重启后从 1 重新开始也没问题——
    /// 服务器在重连接管时会为该玩家重建槽位（<c>LastProcessedSequence</c> 归零）。</para>
    /// </remarks>
    public static class PlayerInputSequence
    {
        private static uint s_Value;

        /// <summary>取下一个输入序号（从 1 开始）。</summary>
        public static uint Next()
        {
            return ++s_Value;
        }

        /// <summary>
        /// 把发号器归零。
        /// </summary>
        /// <remarks>
        /// 只给 EditMode 测试用：静态状态会跨用例残留，不归零会让断言依赖执行顺序。
        /// 运行时代码不许调用它——序号中途归零正是这个类要消灭的缺陷。
        /// </remarks>
        public static void ResetForTests()
        {
            s_Value = 0;
        }
    }
}
